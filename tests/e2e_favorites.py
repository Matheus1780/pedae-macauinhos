"""Favorites, combined filters, sticky search, cart note persistence and narrow layouts."""
import os
from pathlib import Path
from playwright.sync_api import sync_playwright, expect
base=os.environ.get('BASE_URL','http://localhost:19008')
out=Path(os.environ.get('ARTIFACT_DIR','/tmp/pedeae-v13-favorites'));out.mkdir(parents=True,exist_ok=True)
with sync_playwright() as p:
 b=p.chromium.launch(executable_path='/usr/bin/chromium',headless=True,args=['--no-sandbox'])
 page=b.new_page(viewport={'width':390,'height':844},color_scheme='light')
 errors=[];page.on('pageerror',lambda e:errors.append(str(e)))
 page.goto(base,wait_until='networkidle')
 page.get_by_role('button',name='Pular apresentação').click()
 page.get_by_role('button',name='Explorar mercados',exact=True).click()
 page.get_by_role('button',name='Favoritos',exact=True).click()
 expect(page.get_by_text('Guarde os seus preferidos',exact=True)).to_be_visible()
 page.goto(base+'/market/bom-preco',wait_until='networkidle')
 page.get_by_role('button',name='Favoritar Arroz branco Tio João Tipo 1',exact=True).click()
 expect(page.get_by_role('button',name='Desfavoritar Arroz branco Tio João Tipo 1',exact=True)).to_be_visible()
 page.get_by_role('button',name='Favoritos',exact=True).click()
 expect(page.locator('[data-testid^="product-card-"]:visible')).to_have_count(1)
 page.get_by_role('button',name='Adicionar Arroz branco Tio João Tipo 1',exact=True).click()
 expect(page.get_by_test_id('basket-summary').filter(visible=True)).to_contain_text('R$ 31,22')
 page.screenshot(path=str(out/'catalog-favorites.png'))
 page.goto(base+'/favorites',wait_until='networkidle')
 expect(page.locator('[data-testid^="product-card-"]:visible')).to_have_count(1)
 page.reload(wait_until='networkidle')
 expect(page.get_by_role('button',name='Desfavoritar Arroz branco Tio João Tipo 1',exact=True)).to_be_visible()
 page.screenshot(path=str(out/'favorites.png'))
 page.goto(base+'/market/bom-preco',wait_until='networkidle')
 page.get_by_role('button',name='Ordenar ↕',exact=True).click()
 page.get_by_role('radio',name='Menor preço',exact=True).click()
 page.get_by_role('button',name='Em estoque',exact=True).click()
 expect(page.get_by_text('119 produtos',exact=True)).to_be_visible()
 cards=page.locator('[data-testid^="product-card-"]:visible')
 cards.last.scroll_into_view_if_needed()
 expect(page.get_by_label('Buscar neste mercado')).to_be_in_viewport()
 page.get_by_label('Buscar neste mercado').fill('produto inexistente')
 expect(page.get_by_text('Nenhum produto encontrado',exact=True)).to_be_visible()
 page.get_by_role('button',name='Limpar filtros',exact=True).click()
 expect(page.get_by_text('120 produtos',exact=True)).to_be_visible()
 page.get_by_role('button',name='Ver Minha feira',exact=True).click()
 expect(page.get_by_label('Observação: Arroz branco Tio João Tipo 1',exact=True)).to_have_count(0)
 page.get_by_role('button',name='Observação de Arroz branco Tio João Tipo 1',exact=True).click()
 page.get_by_label('Observação: Arroz branco Tio João Tipo 1',exact=True).fill('Embalagem intacta')
 page.get_by_role('button',name='Observação de Arroz branco Tio João Tipo 1',exact=True).click()
 page.reload(wait_until='networkidle')
 expect(page.get_by_text('Embalagem intacta',exact=True)).to_be_visible()
 page.screenshot(path=str(out/'cart-compact.png'))
 page.goto(base+'/favorites',wait_until='networkidle')
 page.get_by_role('button',name='Desfavoritar Arroz branco Tio João Tipo 1',exact=True).click()
 expect(page.get_by_text('Guarde os seus preferidos',exact=True)).to_be_visible()
 # Stock and price labels must remain usable on narrow devices in both palettes.
 for width in [320,390,1280]:
  page.set_viewport_size({'width':width,'height':740})
  for scheme in ['light','dark']:
   page.emulate_media(color_scheme=scheme)
   page.goto(base+'/market/bom-preco',wait_until='networkidle')
   page.screenshot(path=str(out/f'catalog-{width}-{scheme}.png'))
   assert page.evaluate('document.documentElement.scrollWidth <= innerWidth'), 'Horizontal overflow'
   card=page.get_by_test_id('product-card-bom-preco-7').filter(visible=True)
   add=card.get_by_role('button',name='Adicionar Arroz branco Tio João Tipo 1',exact=True)
   rect=card.bounding_box(); target=add.bounding_box()
   assert target['x']>=rect['x'] and target['x']+target['width']<=rect['x']+rect['width']+1
 assert not errors,errors
 print('PASS: favorites persist/remove; combined filters; sticky search; subtotal; notes; 320/390/1280 light/dark')
 b.close()
