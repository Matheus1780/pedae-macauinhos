"""Smoke journey: run with Python + Playwright against `npm run web`.
BASE_URL=http://localhost:19006 python tests/e2e_flow.py
Use only fictitious data. Browser output is written outside the repository.
"""
import os
from pathlib import Path
from playwright.sync_api import sync_playwright, expect

base = os.environ.get('BASE_URL', 'http://localhost:19006')
artifacts = Path(os.environ.get('ARTIFACT_DIR', '/tmp/pedeae-e2e'))
artifacts.mkdir(parents=True, exist_ok=True)
with sync_playwright() as p:
    browser = p.chromium.launch(executable_path=os.environ.get('CHROMIUM_PATH', '/usr/bin/chromium'), headless=True, args=['--no-sandbox'])
    page = browser.new_page(viewport={'width':390,'height':844}, device_scale_factor=1)
    errors = []
    page.on('pageerror', lambda e: errors.append(str(e)))
    page.goto(base, wait_until='networkidle', timeout=90000)
    page.get_by_role('button', name='Pular apresentação').click()
    page.get_by_role('button', name='Explorar mercados', exact=True).click()
    expect(page.get_by_role('button', name='Ver Mercado Bom Preço')).to_be_visible()
    page.screenshot(path=str(artifacts/'home.png'))
    page.get_by_role('button', name='Ver Mercado Bom Preço').click()
    page.get_by_role('button', name='Ver Arroz branco tipo 1').click()
    page.get_by_label('Observações para o mercado').fill('Embalagem sem avarias, por favor.')
    page.get_by_role('button', name='Adicionar à Minha Feira').click()
    page.get_by_role('button', name='Ver Minha feira').click()
    expect(page.get_by_text('R$ 25,90').filter(visible=True).first).to_be_visible()
    page.screenshot(path=str(artifacts/'feira.png'))
    page.get_by_role('button', name='Continuar para entrega').click()
    page.get_by_label('Como podemos chamar você?').fill('Cliente de Teste')
    page.get_by_label('Telefone com DDD').fill('88999990000')
    page.get_by_role('button', name='Receber código', exact=True).click()
    page.get_by_label('Código de verificação').fill('123456')
    page.get_by_role('button', name='Validar código e entrar').click()
    page.get_by_role('button', name='Continuar para entrega').click()
    page.get_by_role('button', name='Adicionar endereço', exact=True).click()
    page.get_by_label('CEP', exact=True).fill('63680000')
    page.get_by_label('Rua ou avenida', exact=True).fill('Rua de Teste')
    page.get_by_label('Número', exact=True).fill('123')
    page.get_by_label('Bairro', exact=True).fill('Centro')
    page.get_by_role('button', name='Salvar endereço').click()
    page.get_by_role('button', name='Entregar em Casa').click()
    page.get_by_role('button', name='Revisar e pagar').click()
    expect(page.get_by_text('R$ 35,90', exact=True).filter(visible=True).first).to_be_visible()
    page.screenshot(path=str(artifacts/'checkout.png'))
    page.get_by_role('button', name='Confirmar pedido').click()
    page.get_by_role('button', name='Simular pagamento aprovado').click()
    page.get_by_role('button', name='Simular: Mercado Preparando').click()
    page.get_by_role('button', name='Simular: Pedido com Entregador').click()
    page.get_by_role('button', name='Simular: A Caminho').click()
    page.screenshot(path=str(artifacts/'tracking.png'))
    page.get_by_role('button', name='Conversar sobre este pedido').click()
    page.get_by_label('Mensagem', exact=True).fill('Estou aguardando. Obrigado!')
    page.get_by_role('button', name='Enviar mensagem').click()
    expect(page.get_by_text('Estou aguardando. Obrigado!', exact=True)).to_be_visible()
    page.get_by_role('button', name='Voltar', exact=True).click()
    page.get_by_role('button', name='Simular: Entregue').click()
    expect(page.get_by_text('Sua feira chegou. Obrigado por comprar local.')).to_be_visible()
    page.reload(wait_until='networkidle')
    expect(page.get_by_text('Sua feira chegou. Obrigado por comprar local.')).to_be_visible()
    page.get_by_role('button', name='Repetir Feira', exact=True).click()
    page.get_by_role('button', name='Montar novamente', exact=True).click()
    expect(page.get_by_text('Arroz branco tipo 1', exact=True).filter(visible=True).first).to_be_visible()
    assert not errors, errors
    print('PASS: onboarding → catalog → cart → OTP → address → checkout → PIX → tracking → chat → delivered → persistence → repeat')
    print('Browser page errors:', errors)
    browser.close()
